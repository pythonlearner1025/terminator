import assert from 'node:assert/strict'
import {createHash} from 'node:crypto'
import {gzipSync,gunzipSync} from 'node:zlib'

export const hash=data=>createHash('sha256').update(data).digest('hex')
export const manifestModule=manifest=>'// Generated by tools/v2/bake-lighting-noise.mjs; do not edit.\nexport const LIGHTING_NOISE_BAKE = '+JSON.stringify(manifest,null,2)+'\n'
export const compressedMetadata=compressed=>({compressedByteLength:compressed.length,compressedSha256:hash(compressed)})

// Gzip encoding is not canonical across Node/zlib/platform versions. Retain an
// existing encoding when its decoded pixels are unchanged, including on rebake.
export function compressLightingNoise(raw,existing){
 if(existing){
  try {if(gunzipSync(existing,{maxOutputLength:raw.length+1}).equals(raw))return existing} catch {}
 }
 return gzipSync(raw,{level:9})
}

export function verifyLightingNoiseBake({compressed,manifest,moduleSource,expectedRaw,expectedManifest}){
 assert.deepEqual(manifest,{...expectedManifest,...compressedMetadata(compressed)},'Stale lighting bake: manifest metadata or compressed digest')
 assert.equal(moduleSource,manifestModule(manifest),'Stale lighting bake: JS/JSON manifest mismatch')
 assert.ok(gunzipSync(compressed,{maxOutputLength:expectedRaw.length+1}).equals(expectedRaw),'Stale lighting bake: decompressed pixels differ from current recipes')
}
